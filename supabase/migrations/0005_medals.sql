-- Medalhas editáveis pela Administração (buff/debuff e a % de cada um).
-- Seguro para executar mais de uma vez: não sobrescreve o que você já editou.

create table if not exists public.medals (
  id integer primary key check (id > 0),
  name text not null,
  sprite_id integer check (sprite_id is null or sprite_id > 0),
  plus_stat text not null,
  plus_value numeric(8, 2) check (plus_value is null or plus_value >= 0),
  minus_stat text,
  minus_value numeric(8, 2) check (minus_value is null or minus_value >= 0),
  updated_at timestamptz not null default now()
);

alter table public.medals enable row level security;

drop policy if exists "Leitura pública" on public.medals;
create policy "Leitura pública"
  on public.medals
  for select
  to anon, authenticated
  using (true);

-- Escritas administrativas são feitas pela rota protegida do servidor.

drop trigger if exists medals_set_updated_at on public.medals;
create trigger medals_set_updated_at
before update on public.medals
for each row execute function public.set_updated_at();

